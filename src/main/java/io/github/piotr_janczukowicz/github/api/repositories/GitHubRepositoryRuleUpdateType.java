package io.github.piotr_janczukowicz.github.api.repositories;

import static io.github.piotr_janczukowicz.util.ValidationUtils.requireNonNull;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonValue;
import io.github.piotr_janczukowicz.openapi.model.CatalogSchema;
import io.github.piotr_janczukowicz.util.EnumUtils;

/** update rule type. */
@CatalogSchema("components/schemas/repository-rule-update/properties/type")
public enum GitHubRepositoryRuleUpdateType {
    UPDATE("update");

    private static final EnumUtils.WireIndex<GitHubRepositoryRuleUpdateType> WIRE_INDEX =
            EnumUtils.index(GitHubRepositoryRuleUpdateType.class, GitHubRepositoryRuleUpdateType::wireValue);

    private final String wireValue;

    GitHubRepositoryRuleUpdateType(final String wireValue) {
        this.wireValue = wireValue;
    }

    /**
     * Value GitHub sends and expects in JSON.
     *
     * @return wire string
     */
    @JsonValue
    public String wireValue() {
        return wireValue;
    }

    /**
     * update rule type from a wire value.
     *
     * @param value JSON value
     * @return matching value
     * @throws NullPointerException if {@code value} is {@code null}
     * @throws IllegalArgumentException if {@code value} is not a known value
     */
    @JsonCreator
    public static GitHubRepositoryRuleUpdateType fromWire(final String value) {
        requireNonNull(value, "value");

        return WIRE_INDEX
                .fromWire(value)
                .orElseThrow(
                        () -> new IllegalArgumentException("Unknown GitHub repository rule update type: " + value));
    }
}
