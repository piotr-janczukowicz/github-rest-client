package io.github.piotr_janczukowicz.github.api.secretscanning;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.github.piotr_janczukowicz.annotation.RecordBuilder;
import io.github.piotr_janczukowicz.openapi.model.CatalogSchema;
import org.jspecify.annotations.Nullable;

/**
 * Secret scanning pattern override.
 *
 * @param tokenType The ID of the pattern.
 * @param customPatternVersion The version of this pattern if it's a custom pattern.
 * @param slug The slug of the pattern.
 * @param displayName The user-friendly name for the pattern.
 * @param alertTotal The total number of alerts generated by this pattern.
 * @param alertTotalPercentage The percentage of all alerts that this pattern represents, rounded to the nearest
 *     integer.
 * @param falsePositives The number of false positive alerts generated by this pattern.
 * @param falsePositiveRate The percentage of alerts from this pattern that are false positives, rounded to the nearest
 *     integer.
 * @param bypassRate The percentage of blocks for this pattern that were bypassed, rounded to the nearest integer.
 * @param defaultSetting The default push protection setting for this pattern.
 * @param enterpriseSetting The push protection setting for this pattern set at the enterprise level. Only present for
 *     partner patterns when the organization has a parent enterprise.
 * @param setting The current push protection setting for this pattern. If this is `not-set`, then it inherits either
 *     the enterprise setting if it exists or the default setting.
 */
@CatalogSchema("components/schemas/secret-scanning-pattern-override")
@JsonInclude(JsonInclude.Include.NON_NULL)
@RecordBuilder
public record GitHubSecretScanningPatternOverride(
        @Nullable String tokenType,
        @Nullable String customPatternVersion,
        @Nullable String slug,
        @Nullable String displayName,
        @Nullable Integer alertTotal,
        @Nullable Integer alertTotalPercentage,
        @Nullable Integer falsePositives,
        @Nullable Integer falsePositiveRate,
        @Nullable Integer bypassRate,
        @Nullable GitHubSecretScanningCustomPatternPushProtectionSetting defaultSetting,
        @Nullable GitHubSecretScanningPatternPushProtectionSetting enterpriseSetting,
        @Nullable GitHubSecretScanningPatternPushProtectionSetting setting) {}
