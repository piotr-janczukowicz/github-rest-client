public enum GitHubJobFilterMode {
    LATEST("latest"),
    ALL("all");

    private static final EnumUtils.WireIndex<GitHubJobFilterMode> WIRE_INDEX =
            EnumUtils.index(GitHubJobFilterMode.class, GitHubJobFilterMode::wireValue);

    private final String wireValue;

    GitHubJobFilterMode(final String wireValue) {
        this.wireValue = wireValue;
    }

    /**
     * Value GitHub sends and expects in JSON.
     *
     * @return wire string
     */
    @JsonValue
    public String wireValue() {
        return wireValue;
    }

    /**
     * Type from a wire value.
     *
     * @param value JSON value
     * @return matching type
     * @throws NullPointerException if {@code value} is {@code null}
     * @throws IllegalArgumentException if {@code value} is not a known type
     */
    @JsonCreator
    public static GitHubJobFilterMode fromWire(final String value) {
        requireNonNull(value, "value");

        return WIRE_INDEX
                .fromWire(value)
                .orElseThrow(() -> new IllegalArgumentException("Unknown GitHubJobFilterMode value: " + value));
    }
}
